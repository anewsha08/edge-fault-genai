"""Quantize the trained MLP to int8 (TFLite), compare accuracy with float, export a C array for the MCU.

Usage (after train.py):
  python ml/quantize_export.py

Outputs in ml/out/: model_int8.tflite, model_data.cc (C array), quant_report.json
"""
import argparse
import json
import os

import numpy as np
import tensorflow as tf


def to_c_array(data: bytes, name="g_fault_model"):
    lines = [f"// Auto-generated by ml/quantize_export.py. Do not edit.",
             f"alignas(16) const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append(f"const unsigned int {name}_len = {len(data)};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="ml/data/features.npz")
    ap.add_argument("--out", default="ml/out")
    args = ap.parse_args()

    d = np.load(args.data, allow_pickle=False)
    X, y = d["X"].astype(np.float32), d["y"].astype(int)
    sc = json.load(open(os.path.join(args.out, "scaler.json")))
    mu, sd = np.array(sc["mean"], np.float32), np.array(sc["std"], np.float32)
    idx = np.load(os.path.join(args.out, "split_idx.npz"))
    Xs = (X - mu) / sd
    tr, te = idx["train"], idx["test"]

    model = tf.keras.models.load_model(os.path.join(args.out, "model.keras"))

    def rep_data():
        for i in np.random.default_rng(0).choice(tr, size=min(500, len(tr)), replace=False):
            yield [Xs[i:i + 1]]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep_data
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tflite = conv.convert()
    with open(os.path.join(args.out, "model_int8.tflite"), "wb") as f:
        f.write(tflite)
    with open(os.path.join(args.out, "model_data.cc"), "w") as f:
        f.write(to_c_array(tflite))

    interp = tf.lite.Interpreter(model_content=tflite)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    s_in, z_in = inp["quantization"]
    preds = []
    for i in te:
        q = np.clip(np.round(Xs[i] / s_in + z_in), -128, 127).astype(np.int8)[None, :]
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        preds.append(int(interp.get_tensor(out["index"]).argmax()))
    int8_acc = float((np.array(preds) == y[te]).mean())
    float_acc = float((model.predict(Xs[te], verbose=0).argmax(1) == y[te]).mean())

    report = {
        "float_test_acc": float_acc,
        "int8_test_acc": int8_acc,
        "accuracy_drop": float_acc - int8_acc,
        "tflite_size_bytes": len(tflite),
        "float_model_params": int(model.count_params()),
        "input_scale": float(s_in), "input_zero_point": int(z_in),
        "note": "Flash size is the .tflite size; RAM/latency must be measured on the MCU (Phase 3 firmware).",
    }
    with open(os.path.join(args.out, "quant_report.json"), "w") as f:
        json.dump(report, f, indent=2)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
